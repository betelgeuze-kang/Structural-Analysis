import { test, expect } from '@playwright/test'
import { intermediateSteelBarCount } from '../../src/workbench-v2/model/rcSteelLayers'

test('intermediate steel quantity retains authored layers', () => {
  const section = { depth_m: 0.4, cover_m: 0.04 }
  expect(intermediateSteelBarCount(section)).toBe(0)
  expect(intermediateSteelBarCount({ ...section, intermediate_steel_layers: [
    { y_m: -0.05, bar_count: 2 }, { y_m: 0.05, bar_count: 2 },
  ] })).toBe(4)
})
for (const [name, layers] of Object.entries({
  null: null, empty: [], boolean: [{ y_m: 0, bar_count: true }],
  duplicate: [{ y_m: 0, bar_count: 2 }, { y_m: 0, bar_count: 2 }],
  outside: [{ y_m: 0.18, bar_count: 2 }], reverse: [{ y_m: 0.05, bar_count: 2 }, { y_m: -0.05, bar_count: 2 }],
  unknown: [{ y_m: 0, bar_count: 2, area: 1 }],
})) test(`intermediate steel rejects ${name}`, () => {
  expect(() => intermediateSteelBarCount({ depth_m: 0.4, cover_m: 0.04, intermediate_steel_layers: layers })).toThrow()
})

// Generated by the actual public API and full reference comparison, not hand-edited rows.
test('intermediate steel actual comparison preserves reviewed quantities and costs', async () => {
  const { readFileSync } = await import('node:fs')
  const { gunzipSync } = await import('node:zlib')
  const { createHash } = await import('node:crypto')
  const { validateDesignComparisonManifest, validateDesignComparisonReport } = await import('../../src/workbench-v2/model/designComparisonSchema')
  const raw = gunzipSync(readFileSync('tests/frontend/fixtures/intermediate-steel-comparison.json.gz'))
  const report = JSON.parse(raw.toString('utf8'))
  const manifest = validateDesignComparisonManifest({
    schema_version: 'rc-fiber-design-comparison-bundle.v1', source_revision: report.identity.source_revision,
    report_file: 'comparison.json', report_byte_length: raw.length,
    report_sha256: `sha256:${createHash('sha256').update(raw).digest('hex')}`,
    report_hash: report.report_hash, experiment_identity_hash: report.experiment_identity_hash,
  })
  expect(validateDesignComparisonReport(report, manifest)).toBe(report)
  const rows = report.rows
  expect(rows).toHaveLength(2)
  expect(rows[0].quantities.totals.longitudinal_rebar_mass_kg).toBe(rows[1].quantities.totals.longitudinal_rebar_mass_kg)
  expect(rows[1].material_estimate.total).toBeLessThan(rows[0].material_estimate.total)
  expect(rows[1].canonical_model.sections[0].intermediate_steel_layers).toEqual(rows[0].canonical_model.sections[0].intermediate_steel_layers)
})
